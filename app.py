import streamlit as st
from google import genai
from google.genai import types
from PIL import Image


# ==========================================
# 1. 페이지 설정
# ==========================================

st.set_page_config(
    page_title="서울문화재단 AI 시설민원 지원",
    page_icon="🏢",
    layout="centered"
)


# ==========================================
# 2. Gemini API 연결
# ==========================================

try:
    GEMINI_API_KEY = st.secrets["GEMINI_API_KEY"]

    client = genai.Client(
        api_key=GEMINI_API_KEY
    )

except Exception:
    st.error("⚠️ Gemini API Key가 설정되지 않았습니다.")
    st.info("Streamlit의 Manage app → Settings → Secrets에서 GEMINI_API_KEY를 등록해주세요.")
    st.stop()


# ==========================================
# 3. AI 판단 기준
# ==========================================

SYSTEM_PROMPT = """
당신은 서울문화재단의 'AI 시설민원 초기 대응 지원 AI'입니다.

이 시스템의 목적은 다음과 같습니다.

"시설 이상 발생 시 비전문가인 공간 담당자가 초기 대응을 할 수 있도록 안내하고,
시설관리 담당자가 신속하고 정확하게 상황을 파악하여 적절한 후속 조치를 할 수 있도록 지원하는 것."

가장 중요한 원칙:

1. 정확한 고장 원인을 AI가 단정하지 않는다.
2. 비전문가가 직접 수리하거나 분해하는 방법을 안내하지 않는다.
3. 전기, 가스, 배관, 기계장치 등 위험한 작업을 공간 담당자에게 시키지 않는다.
4. 가장 먼저 "지금 공간에서 해야 할 일"을 명확하게 안내한다.
5. 추가 피해와 안전사고를 예방하는 조치를 우선한다.
6. 시설관리 담당자가 현장 상황을 빠르게 파악할 수 있도록 민원 내용을 구조화한다.
7. 전문적인 수리나 고장 원인 확인이 필요한 경우
   "시설관리 담당자 확인 후 전문 유지보수 업체 점검 요청 검토"
   방식으로 안내한다.

답변 시 고장 원인을 확정적으로 말하지 마십시오.

예시:

잘못된 표현:
"배수관이 막혔습니다."

올바른 표현:
"배수계통 이상 가능성이 있으므로 현장 확인이 필요합니다."

반드시 아래 형식으로 답변하십시오.


## 현재 상황

민원 내용을 비전문가도 이해하기 쉽게 1~2문장으로 정리합니다.


## 공간에서 지금 할 일 ★

공간 담당자가 즉시 할 수 있는 초기 대응을
우선순위대로 3~5개 작성합니다.

예시:
1. 해당 시설 사용을 중단합니다.
2. 이용객 접근이 필요한 경우 안전하게 통제합니다.
3. 물기, 장애물 등 추가 피해 요인을 제거합니다.

단, 상황에 맞는 조치만 작성합니다.


## 확인해볼 사항

공간 담당자가 안전한 범위에서 확인할 수 있는 사항을
질문 형태로 작성합니다.

예시:
- 물이 계속 떨어지고 있나요?
- 이상 현상이 특정 시간에 반복되나요?
- 주변 콘센트나 전선에 물이 닿았나요?

전문적인 점검이나 분해가 필요한 사항은 포함하지 않습니다.


## 주의사항

비전문가가 하면 안 되는 행동과 안전상 주의사항을 작성합니다.


## 시설 분야

- 주관 분야:
- 연계 가능 분야:
- 정확한 원인: 현장 확인 필요

시설 분야는 다음 중 적절하게 판단합니다.

- 건축/영선
- 기계설비
- 전기
- 소방
- 통신
- 승강기
- 기타


## 시설관리 담당자 전달 내용

다음 항목으로 정리합니다.

- 발생 공간:
- 발생 위치:
- 현재 증상:
- 발생 범위:
- 이용자/운영 영향:
- 현재 조치:

사용자가 입력하지 않은 정보는
"추가 확인 필요"라고 표시합니다.


## 후속 조치 방향

시설관리 담당자가 검토해야 할 조치를 작성합니다.

예시:
- 현장 확인
- 시설 상태 점검
- 필요 시 전문 유지보수 업체 점검 요청

반드시 원인을 확정하지 말고
"점검 필요", "확인 필요", "가능성" 등의 표현을 사용합니다.


## 최종 원칙

이 시스템은 고장 원인을 진단하거나
전문 수리를 대신하는 시스템이 아닙니다.

공간 담당자의 안전한 초기 대응과
시설관리 담당자의 상황 파악을 지원하는 것을 목적으로 합니다.
"""


# ==========================================
# 4. 화면 제목
# ==========================================

st.title("🏢 서울문화재단 AI 시설민원 지원")

st.caption(
    "시설 이상 발생 시 초기 대응을 안내하고 "
    "시설관리 담당자의 신속한 후속 조치를 지원합니다."
)


# ==========================================
# 5. 시설 이상 접수
# ==========================================

st.divider()

st.subheader("📝 시설 이상 접수")


spaces = [
    "본관",
    "대학로센터",
    "서울연극센터",
    "서울장애예술창작센터",
    "청년예술청",
    "연희문학창작촌",
    "서울무용센터",
    "서울연극창작센터",
    "리스테이지 서울",
    "예술교육센터 강북",
    "문래예술공장",
    "금천예술공장",
    "예술교육센터 용산",
    "노들섬",
    "서울거리예술창작센터",
    "예술교육센터 양천",
    "예술교육센터 은평",
    "신당창작아케이드",
    "예술교육센터 서초"
    "기타 / 직접 입력"
]


space_select = st.selectbox(
    "발생 공간",
    spaces
)


if space_select == "기타 / 직접 입력":

    space = st.text_input(
        "공간명을 입력해주세요"
    )

else:

    space = space_select


location = st.text_input(
    "발생 위치",
    placeholder="예: 4층 화장실 앞"
)


complaint = st.text_area(
    "민원 내용",
    placeholder="예: 에어컨에서 물이 계속 떨어져요. 바닥이 젖어 있습니다.",
    height=150
)


uploaded_file = st.file_uploader(
    "사진 첨부 (선택)",
    type=["jpg", "jpeg", "png"]
)


# ==========================================
# 6. AI 분석
# ==========================================

if st.button(
    "🤖 AI 초기 대응 분석하기",
    use_container_width=True
):

    if not space:

        st.warning("발생 공간을 입력해주세요.")

    elif not location:

        st.warning("발생 위치를 입력해주세요.")

    elif not complaint:

        st.warning("민원 내용을 입력해주세요.")

    else:

        with st.spinner("AI가 시설 상황을 분석하고 있습니다..."):

            user_prompt = f"""
[시설 이상 접수 정보]

발생 공간:
{space}

발생 위치:
{location}

민원 내용:
{complaint}

위 내용을 바탕으로
시설 이상 초기 대응 가이드에 따라 분석해주세요.
"""

            contents = [user_prompt]

            # 사진 첨부 시 함께 분석
            if uploaded_file is not None:

                image = Image.open(uploaded_file)

                contents.append(image)

                contents.append(
                    "첨부된 사진도 참고하여 상황을 분석하세요. "
                    "사진만으로 정확한 고장 원인을 단정하지 마십시오."
                )

            try:

                response = client.models.generate_content(

                    model="gemini-3.7-flash",

                    contents=contents,

                    config=types.GenerateContentConfig(

                        system_instruction=SYSTEM_PROMPT,

                        temperature=0.2,

                        max_output_tokens=3000

                    )

                )


                # ==========================================
                # 7. 결과 출력
                # ==========================================

                st.divider()

                st.subheader("🤖 AI 분석 결과")

                st.markdown(response.text)

                st.divider()

                st.caption(
                    "※ 본 서비스는 시설관리 담당자의 판단을 지원하기 위한 초기 대응 도구입니다. "
                    "정확한 원인 판단 및 전문적인 조치는 현장 확인 후 결정해야 합니다."
                )


            except Exception as e:

                st.error("AI 분석 중 오류가 발생했습니다.")

                st.error(str(e))
